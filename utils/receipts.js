// PDF documents: the patient's payment receipt for a booking, and the doctor's monthly payout statement.
// (the header, footer and small helpers are shared with the patient report, utils/patientReportPdf.js)
import { createPdf } from "./pdf.js";
import { moneyOf } from "./earnings.js";
import { typeLabel } from "./consultation.js";

export const BLUE = [0.21, 0.45, 0.67];
export const GREY = [0.42, 0.47, 0.55];
const rupees = amount => `Rs. ${Number(amount || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
export const day = date => new Date(date).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric", timeZone: "Asia/Kolkata" });
export const slotDay = date => new Date(`${date}T00:00:00Z`).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
const SHORT_TYPES = { clinic: "Clinic", video: "Video", "quick-call": "Quick call" };
export const clock = time => {
  const [hours, minutes] = String(time || "0:0").split(":").map(Number);
  return `${hours % 12 || 12}:${String(minutes).padStart(2, "0")} ${hours >= 12 ? "pm" : "am"}`;
};

export const header = (pdf, title, subtitle) => {
  pdf.box(0, 0, pdf.width, 92, { fill: [0.93, 0.96, 0.99] });
  pdf.text("Medora", 48, 46, { size: 22, bold: true, color: BLUE });
  pdf.text("Online doctor consultations", 48, 64, { size: 9, color: GREY });
  pdf.text(title, pdf.width - 48, 46, { size: 16, bold: true, align: "right" });
  pdf.text(subtitle, pdf.width - 48, 64, { size: 9, color: GREY, align: "right" });
};

export const footer = (pdf, note) => {
  pdf.line(48, 790, pdf.width - 48, 790);
  pdf.text(note, 48, 806, { size: 8, color: GREY });
  pdf.text("Medora · hello@medora.health · This document was generated by Medora.", 48, 818, { size: 8, color: GREY });
};

export const pair = (pdf, label, value, x, y) => {
  pdf.text(label.toUpperCase(), x, y, { size: 7.5, bold: true, color: GREY });
  pdf.text(value, x, y + 14, { size: 10.5, maxWidth: 250 });
};

// the patient's receipt for one paid booking
export const receiptPdf = ({ booking, doctor, patient }) => {
  const pdf = createPdf();
  const money = moneyOf(booking);
  const number = `MED-${String(booking._id).slice(-8).toUpperCase()}`;
  header(pdf, "Payment receipt", `${number} · paid ${day(booking.createdAt)}`);

  pair(pdf, "Billed to", patient?.name || "Patient", 48, 130);
  pair(pdf, "Visit for", booking.familyMember?.name ? `${booking.familyMember.name} (${booking.familyMember.relation})` : patient?.name || "Patient", 310, 130);
  pair(pdf, "Doctor", `${doctor?.name || "Doctor"}${doctor?.specialization ? `, ${doctor.specialization}` : ""}`, 48, 176);
  pair(pdf, "Registration no.", doctor?.registrationNumber || "-", 310, 176);
  pair(pdf, "Appointment", `${typeLabel(booking.consultationType)} · ${slotDay(booking.appointmentDate)} at ${clock(booking.appointmentTime)}`, 48, 222);
  pair(pdf, "Status", booking.status === "cancelled" ? `Cancelled${booking.cancelledBy ? ` by the ${booking.cancelledBy}` : ""}` : booking.status === "approved" ? "Confirmed" : "Waiting for the doctor", 310, 222);

  // amounts
  let y = 290;
  pdf.box(48, y - 16, pdf.width - 96, 24, { fill: [0.95, 0.97, 0.99] });
  pdf.text("Description", 58, y, { size: 9, bold: true, color: GREY });
  pdf.text("Amount", pdf.width - 58, y, { size: 9, bold: true, color: GREY, align: "right" });
  const row = (label, amount, options = {}) => {
    y += 26;
    pdf.text(label, 58, y, { size: 10.5, ...options });
    pdf.text(amount, pdf.width - 58, y, { size: 10.5, align: "right", ...options });
    pdf.line(48, y + 9, pdf.width - 48, y + 9);
  };
  row(`${typeLabel(booking.consultationType)} fee`, rupees(booking.listPrice || booking.ticketPrice));
  if (booking.familyDiscount) row("Plus Family discount (5%)", `- ${rupees(booking.familyDiscount)}`, { color: [0.1, 0.5, 0.3] });
  row("Paid by card (Stripe)", rupees(money.paid), { bold: true });
  if (money.refunded > 0) row(`Refunded${booking.refundCovered ? ` (incl. ${rupees(booking.refundCovered)} from your membership)` : ""}`, `- ${rupees(money.refunded)}`, { color: [0.1, 0.5, 0.3] });
  y += 34;
  pdf.text("Total charged", 58, y, { size: 13, bold: true });
  pdf.text(rupees(money.kept), pdf.width - 58, y, { size: 13, bold: true, align: "right" });

  y += 44;
  pdf.text("Payment", 48, y, { size: 7.5, bold: true, color: GREY });
  pdf.text(`Card payment through Stripe${booking.paymentIntent ? `, reference ...${String(booking.paymentIntent).slice(-10)}` : ""}.`, 48, y + 14, { size: 10 });
  if (booking.refundId) pdf.text(`Refunds reach the card in 5-10 working days (refund reference ...${String(booking.refundId).slice(-10)}).`, 48, y + 30, { size: 10 });

  footer(pdf, "This is a payment receipt for an online consultation booked on Medora, not a tax invoice. Demo: test payments, no real money.");
  return pdf.toBuffer();
};

// the doctor's payout statement for one month: every booking with its split, and the totals
export const statementPdf = ({ doctor, month, bookings }) => {
  const pdf = createPdf();
  const monthName = new Date(`${month}-01T00:00:00Z`).toLocaleDateString("en-IN", { month: "long", year: "numeric", timeZone: "UTC" });
  header(pdf, "Payout statement", monthName);
  pair(pdf, "Doctor", doctor.name, 48, 130);
  pair(pdf, "Paid out through", doctor.payoutsEnabled ? "Stripe Connect (automatic, per booking)" : "Held by Medora until a payout account is connected", 310, 130);

  const totals = { fee: 0, platform: 0, refunded: 0, doctor: 0 };
  const columns = [
    { label: "Date", x: 48 },
    { label: "Patient", x: 118 },
    { label: "Visit", x: 238 },
    { label: "Fee", x: 352, align: "right" },
    { label: "Refunded", x: 420, align: "right" },
    { label: "Medora fee", x: 486, align: "right" },
    { label: "Your share", x: pdf.width - 48, align: "right" },
  ];
  let y = 196;
  const tableHeader = () => {
    pdf.box(40, y - 14, pdf.width - 80, 22, { fill: [0.95, 0.97, 0.99] });
    columns.forEach(column => pdf.text(column.label, column.x, y, { size: 8, bold: true, color: GREY, align: column.align || "left" }));
  };
  tableHeader();
  for (const booking of bookings) {
    const money = moneyOf(booking);
    const fee = booking.listPrice || booking.ticketPrice;
    totals.fee += fee;
    totals.platform += money.platform;
    totals.refunded += money.refunded;
    totals.doctor += money.doctor;
    y += 20;
    if (y > 760) {
      pdf.addPage();
      y = 60;
      tableHeader();
      y += 20;
    }
    const patientName = booking.familyMember?.name || booking.user?.name || "Patient";
    pdf.text(new Date(`${booking.appointmentDate}T00:00:00Z`).toLocaleDateString("en-IN", { day: "numeric", month: "short", timeZone: "UTC" }), 48, y, { size: 9 });
    pdf.text(patientName, 118, y, { size: 9, maxWidth: 112 });
    pdf.text(`${SHORT_TYPES[booking.consultationType] || "Visit"}${booking.status === "cancelled" ? ", cancelled" : ""}`, 238, y, { size: 9, maxWidth: 80 });
    pdf.text(rupees(fee).replace("Rs. ", ""), 352, y, { size: 9, align: "right" });
    pdf.text(money.refunded ? rupees(money.refunded).replace("Rs. ", "") : "-", 420, y, { size: 9, align: "right" });
    pdf.text(rupees(money.platform).replace("Rs. ", ""), 486, y, { size: 9, align: "right" });
    pdf.text(rupees(money.doctor).replace("Rs. ", ""), pdf.width - 48, y, { size: 9, bold: true, align: "right" });
    pdf.line(40, y + 7, pdf.width - 40, y + 7, { color: [0.92, 0.94, 0.96] });
  }
  if (!bookings.length) {
    y += 24;
    pdf.text("No paid bookings this month.", 48, y, { size: 10, color: GREY });
  }
  y = Math.min(y + 40, 740);
  pdf.text(`${bookings.length} booking${bookings.length === 1 ? "" : "s"}`, 48, y, { size: 10, bold: true });
  pdf.text(`Fees ${rupees(totals.fee)} · refunded ${rupees(totals.refunded)} · Medora fee ${rupees(totals.platform)}`, 48, y + 16, { size: 9, color: GREY });
  pdf.text("Your share", pdf.width - 48, y, { size: 9, bold: true, color: GREY, align: "right" });
  pdf.text(rupees(totals.doctor), pdf.width - 48, y + 18, { size: 15, bold: true, align: "right", color: BLUE });

  footer(pdf, "Amounts in rupees. Medora's fee is the plan's commission; Plus Family discounts and extra membership refunds are paid by Medora.");
  return { buffer: pdf.toBuffer(), totals: Object.fromEntries(Object.entries(totals).map(([key, value]) => [key, Math.round(value * 100) / 100])) };
};
